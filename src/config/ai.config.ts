/**
 * Получить список всех активных моделей с учетом переменных окружения
 */
export function getAvailableModels(): OpenRouterModelConfig[] {
  const baseModels = CONFIGURED_OPENROUTER_MODELS.filter((m) => m.enabled);

  // Опционально: добавление моделей из переменной окружения OPENROUTER_EXTRA_MODELS (через запятую)
  if (process.env.OPENROUTER_EXTRA_MODELS) {
    const extraIds = process.env.OPENROUTER_EXTRA_MODELS.split(",").map((s) => s.trim());
    for (const extraId of extraIds) {
      if (extraId && !baseModels.some((m) => m.id === extraId)) {
        baseModels.push({
          id: extraId,
          name: extraId.split("/")[1] || extraId,
          badge: "Внешняя",
          description: "Модель подключена через переменную OPENROUTER_EXTRA_MODELS",
          isFree: extraId.endsWith(":free"),
          enabled: true,
        });
      }
    }
  }

  return baseModels;
}

